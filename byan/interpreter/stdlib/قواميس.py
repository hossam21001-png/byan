# -*- coding: utf-8 -*-
"""وحدة القواميس"""


def مفاتيح(قاموس):
    """المفاتيح"""
    return list(قاموس.keys())


def قيم(قاموس):
    """القيم"""
    return list(قاموس.values())


def عناصر(قاموس):
    """العناصر"""
    return list(قاموس.items())


def دمج(*قواميس):
    """دمج"""
    result = {}
    for q in قواميس:
        result.update(q)
    return result


def يحتوي_مفتاح(قاموس, مفتاح):
    """هل يحتوي؟"""
    return مفتاح in قاموس


def احذف_مفتاح(قاموس, مفتاح):
    """حذف"""
    return قاموس.pop(مفتاح, None)


def اقلب(قاموس):
    """عكس (قيمة→مفتاح)"""
    return {v: k for k, v in قاموس.items()}


def نسخ(قاموس):
    """نسخة"""
    return dict(قاموس)


def امسح(قاموس):
    """تفريغ"""
    قاموس.clear()
    return قاموس


def طول(قاموس):
    """عدد العناصر"""
    return len(قاموس)


def احصل(قاموس, مفتاح, افتراضي=None):
    """جلب مع افتراضي"""
    return قاموس.get(مفتاح, افتراضي)


